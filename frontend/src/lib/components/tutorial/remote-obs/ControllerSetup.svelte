<h1 class="text-2xl font-semibold">Setting Up Controller Commands</h1>

<h2>
	Go to <b>OBS</b> → <b>OBS Settings</b> → <b>Controller Commands</b>.
</h2>

<h2>
	Toggle <b>Enable Controller Commands</b> to activate the feature. Your controller inputs will now
	be monitored while Dolphin is running.
</h2>

<h2>
	Click <b>Add New Command</b> to create a trigger. You will see a list of all GameCube controller
	buttons — check the buttons you want to use as a combo.
</h2>

<h2>
	Choose a combination that is unlikely to occur naturally during gameplay. Common choices:
</h2>

<ul>
	<li><b>L + R + Start</b> — save replay buffer</li>
	<li><b>L + R + Z</b> — toggle a scene item (e.g. webcam)</li>
	<li><b>L + R + A</b> — switch to a specific OBS scene</li>
</ul>

<h2>
	After selecting your buttons, pick the <b>OBS command</b> to execute, then click <b>Add
		Command</b>.
</h2>

<h2>
	The active button icons on each saved command light up when those buttons are held — useful for
	confirming your controller is recognised.
</h2>
