<h1 class="text-2xl font-semibold">Remote Control OBS</h1>

<h2>
	This tutorial covers two ways to trigger <b>OBS</b> actions without touching your keyboard or
	mouse during a match.
</h2>

<ul>
	<li><b>Controller Commands</b> — hold a button combo on your GameCube controller to fire an OBS command (e.g. save replay buffer, mute mic, switch scene)</li>
	<li><b>Scene Switch Commands</b> — OBS commands that run automatically whenever Froggi detects a game-state change (game starts, game ends, rank change, etc.)</li>
</ul>

<h2>
	Both features require an active <b>OBS WebSocket</b> connection. Make sure OBS is connected
	before testing.
</h2>

<h2>
	Controller Commands also require <b>Dolphin</b> to be open so Froggi can read your controller
	inputs. This feature is <b>Windows only</b>.
</h2>
