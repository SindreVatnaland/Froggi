<h1 class="text-2xl font-semibold">Online tournaments</h1>

<h2>
	For online play, Froggi integrates with <b>ngrok</b>
	to generate a public URL that players can open from
	<b>anywhere on the internet</b>
	 — no shared Wi-Fi needed.
</h2>

<h2>
	Head to <b>Settings → Remote Access</b>
	 in Froggi to get started.
</h2>

<h2>
	Once ngrok is active, Froggi detects it automatically and the Stage Striking dashboard shows the
	public player URLs. Tap a QR code to copy the link and share it with players via Discord or
	chat.
</h2>

<h2>
	The URL is <b>temporary</b>
	 — it changes every time froggi restarts or a new match is detected. Share a fresh link with players
	at the start of each session.
</h2>
