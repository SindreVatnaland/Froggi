<h1 class="text-2xl font-semibold">RPS and stage striking</h1>

<h2>
	Once the set starts, players go through <b>RPS → Stage Striking → Character Select</b>
	entirely on their phones. The TO watches the progress on the dashboard.
</h2>

<h2>RPS:</h2>
<ul>
	<li>Each player picks Rock, Paper, or Scissors on their phone</li>
	<li>A 5-second countdown auto-picks randomly if a player doesn't choose in time</li>
	<li>If it's a tie, they go again automatically</li>
	<li>The winner chooses strike order</li>
</ul>

<h2>Stage striking (Game 1):</h2>
<ul>
	<li>RPS winner strikes 1, then the other player strikes 2, then RPS winner strikes 1 — leaving 1 starter</li>
	<li>Struck stages are dimmed on both players' screens</li>
	<li>The phone shows <i>"Opponent is striking…"</i> when it's not your turn</li>
</ul>

<h2>Character select:</h2>
<ul>
	<li>Game 1 uses <b>double blind</b> — both players pick simultaneously without seeing each other's choice</li>
	<li>Later games use the <b>winner locks, loser picks</b> format</li>
	<li>Tapping a character shows a preview with Confirm / Cancel before it's submitted</li>
</ul>

<h2>
	Once characters are locked in, both phones show <b>Game [N] — Playing</b> with the stage and
	characters. Time to play the game.
</h2>
