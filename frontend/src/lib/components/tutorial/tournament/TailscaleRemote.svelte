<h1 class="text-2xl font-semibold">Remote dashboard control</h1>

<h2>
	With <b>Tailscale</b> enabled, you can control the Froggi dashboard from any device — your
	phone, a laptop across the venue, or anywhere over the internet.
</h2>

<h2>How to get the link:</h2>
<ol>
	<li>Click the <b>mobile icon</b> in the Froggi navbar</li>
	<li>Switch to the <b>Remote</b> tab (only visible when Tailscale is connected)</li>
	<li>Copy the URL and open it on any device</li>
</ol>

<h2>
	The Tailscale URL is <b>permanent</b> — it never changes between sessions. You can bookmark it
	or share it with a co-TO so they can follow along or take over from their own device.
</h2>
