<h1 class="text-2xl font-semibold">Running a tournament with Froggi</h1>

<h2>
	This tutorial covers how to use Froggi as a <b>Tournament Organizer</b>
	running
	<b>Melee sets</b>
	 with automatic stage striking, character selection, and score tracking.
</h2>

<h2>You will learn how to:</h2>
<ul>
	<li>Share stage striking links to players on their phones</li>
	<li>Run offline and online tournaments</li>
	<li>Manage sets from the TO dashboard</li>
</ul>

<h2>What you need:</h2>
<ul>
	<li>
		<b>Froggi</b>
		 running on your streaming PC
	</li>
	<li>
		<b>Slippi</b>
		 installed (spectate folder is configured automatically)
	</li>
	<li>Players with a phone or device that can open a web browser</li>
	<li>
		<b>ngrok</b>
		 or
		<b>Tailscale</b>
		 for online play (explained later in this tutorial)
	</li>
</ul>
