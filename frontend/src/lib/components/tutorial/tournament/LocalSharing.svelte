<h1 class="text-2xl font-semibold">Share links — local (same network)</h1>

<h2>
	When players are on the <b>same Wi-Fi</b> as your PC, no extra software is needed. Froggi
	generates player URLs automatically.
</h2>

<h2>Steps:</h2>
<ol>
	<li>
		Open Froggi and navigate to <b>Stage Striking</b>
	</li>
	<li>
		Two QR codes appear on the dashboard — one for <b>Player 1</b> and one for <b>Player 2</b>
	</li>
	<li>
		Each player <b>scans their QR code</b> with their phone camera and opens the link
	</li>
	<li>
		The phone becomes their stage striking remote — they'll do RPS, strike/pick stages, and select
		characters from it
	</li>
</ol>

<h2>
	You can also <b>tap the QR code</b> to copy the URL and paste it into a chat if scanning isn't
	convenient.
</h2>

<h2>
	The TO manages everything else from the Froggi dashboard — starting the set, reporting game
	winners, and resetting between sets.
</h2>
