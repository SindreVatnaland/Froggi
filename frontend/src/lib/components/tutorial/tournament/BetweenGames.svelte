<h1 class="text-2xl font-semibold">Between games</h1>

<h2>
	After each game, the TO reports the result on the dashboard. The players' phones then
	automatically advance to the next stage in the process.
</h2>

<h2>TO actions:</h2>
<ol>
	<li>
		On the dashboard, click <b>[Player Name] wins</b> for the game winner
	</li>
	<li>
		If a game was a warmup / not counted, click <b>Warmup</b> instead — the score won't change
		and the game flow restarts from character select
	</li>
</ol>

<h2>What happens next on the phones:</h2>
<ul>
	<li><b>Winner</b> bans 1 stage from the full legal pool (Dave's Stupid Rule applies — winner can't pick a stage they already won on)</li>
	<li><b>Loser</b> picks from the remaining stages</li>
	<li>Winner locks their character first, then loser counterpicks</li>
</ul>

<h2>
	The TO dashboard shows the current stage and characters at all times so you always know what's
	happening.
</h2>

<h2>
	If the set is over, click <b>New Set</b> to reset. The dashboard returns to the lobby and the
	phones show the set result.
</h2>
