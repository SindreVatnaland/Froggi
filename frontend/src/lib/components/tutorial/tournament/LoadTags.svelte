<h1 class="text-2xl font-semibold">Local tournaments</h1>

<h2>
	For in-person events, no extra software is needed. Froggi generates player URLs automatically
	using your local network address.
</h2>

<h2>Setup:</h2>
<ol>
	<li>Make sure your PC and the players' phones are on the <b>same Wi-Fi network</b></li>
	<li>Open Froggi and navigate to <b>Stage Striking</b></li>
	<li>Two QR codes appear — one for <b>Player 1</b> and one for <b>Player 2</b></li>
	<li>Both players scan their QR code and open the link on their phone</li>
	<li>The TO clicks <b>Start Set</b> and enters the player names</li>
</ol>

<h2>
	The QR codes also work great on <b>fixed devices</b> — a tablet or second screen placed at the
	setup that players can scan when they sit down, without needing to share anything manually.
</h2>

<h2>
	You can also <b>tap a QR code</b> to copy the URL and paste it into a chat if scanning isn't
	convenient.
</h2>

<h2>Using Tailscale?</h2>
<h2>
	If you have <b>Tailscale</b> installed and enabled in <b>Settings → Remote Access</b>, Froggi
	generates a persistent public URL instead of a local one. Players can connect from
	<b>any network</b> — no shared Wi-Fi or same router required. Everything else works the same.
</h2>
