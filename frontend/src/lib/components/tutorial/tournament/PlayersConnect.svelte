<h1 class="text-2xl font-semibold">Players open their links</h1>

<h2>
	Each player opens their URL on their phone (or any browser). The page shows a
	<b>waiting screen</b> while it waits for both players to connect.
</h2>

<h2>What the lobby screen shows:</h2>
<ul>
	<li>A green dot when <b>you</b> are connected</li>
	<li>A blinking dot while waiting for <b>your opponent</b> to connect</li>
	<li>
		A message: <i>"Waiting for the TO to start the set."</i>
	</li>
</ul>

<h2>
	Both players should wait on this screen until the TO is ready. The set won't start until the TO
	clicks <b>Start Set</b> on the dashboard — players can't accidentally trigger anything from the
	lobby.
</h2>

<h2>
	The TO can see which players have connected on the dashboard. Once both show as connected, you're
	ready to start.
</h2>
