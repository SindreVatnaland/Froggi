<h1 class="text-2xl font-semibold">Starting a set</h1>

<h2>
	When both players are on the lobby screen and you've spectated their Direct Play session, you're
	ready to start.
</h2>

<h2>Steps:</h2>
<ol>
	<li>
		On the Froggi dashboard, go to <b>Stage Striking</b>
	</li>
	<li>
		Check that the <b>Player 1</b> and <b>Player 2</b> name fields are filled in — Froggi
		auto-fills them from the last spectated session
	</li>
	<li>Edit the names if needed (for example, if you want to use display names instead of Slippi tags)</li>
	<li>
		Select <b>BO3</b> or <b>BO5</b>
	</li>
	<li>
		Click <b>Start Set</b>
	</li>
</ol>

<h2>
	Both players' phones will immediately advance out of the lobby screen and into
	<b>Rock · Paper · Scissors</b>.
</h2>

<h2>
	From this point, the players handle everything on their phones. The TO just watches the dashboard
	and reports game results.
</h2>
